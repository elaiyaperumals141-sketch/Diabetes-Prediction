
import streamlit as st
import pandas as pd
import joblib
import numpy as np

# Load trained model
model_data = joblib.load("diabetes_model.pkl")

model = model_data["model"]
fill_values = model_data["fill_values"]
input_columns = model_data["input_columns"]
invalid_zero_columns = model_data["invalid_zero_columns"]

# Page configuration
st.set_page_config(
    page_title="Diabetes Prediction",
    page_icon="🩺",
    layout="centered"
)

# Application title
st.title("🩺 Diabetes Prediction")
st.subheader("Machine Learning using Decision Tree Classifier")

st.write(
    "Enter the following health-related measurements "
    "to see the prediction generated by the trained model."
)

st.divider()

# Input section
st.header("Patient Information")

col1, col2 = st.columns(2)

with col1:

    pregnancies = st.number_input(
        "Pregnancies",
        min_value=0,
        max_value=20,
        value=1,
        step=1
    )

    glucose = st.number_input(
        "Glucose",
        min_value=0.0,
        max_value=500.0,
        value=120.0,
        step=1.0
    )

    blood_pressure = st.number_input(
        "Blood Pressure",
        min_value=0.0,
        max_value=250.0,
        value=70.0,
        step=1.0
    )

    skin_thickness = st.number_input(
        "Skin Thickness",
        min_value=0.0,
        max_value=150.0,
        value=20.0,
        step=1.0
    )

with col2:

    insulin = st.number_input(
        "Insulin",
        min_value=0.0,
        max_value=1000.0,
        value=80.0,
        step=1.0
    )

    bmi = st.number_input(
        "BMI",
        min_value=0.0,
        max_value=100.0,
        value=25.0,
        step=0.1
    )

    diabetes_pedigree = st.number_input(
        "Diabetes Pedigree Function",
        min_value=0.0,
        max_value=5.0,
        value=0.5,
        step=0.01
    )

    age = st.number_input(
        "Age",
        min_value=1,
        max_value=120,
        value=30,
        step=1
    )

st.divider()

# Prediction button
if st.button(
    "🔍 Predict Diabetes",
    use_container_width=True
):

    # Create input dataframe
    new_patient = pd.DataFrame({
        "Pregnancies": [pregnancies],
        "Glucose": [glucose],
        "BloodPressure": [blood_pressure],
        "SkinThickness": [skin_thickness],
        "Insulin": [insulin],
        "BMI": [bmi],
        "DiabetesPedigreeFunction": [diabetes_pedigree],
        "Age": [age]
    })

    # Replace invalid zeros with NaN
    new_patient[invalid_zero_columns] = new_patient[
        invalid_zero_columns
    ].replace(0, np.nan)

    # Apply the same imputation values used during training
    for column in input_columns:
        new_patient[column] = new_patient[column].fillna(
            fill_values[column]
        )

    # Ensure correct column order
    new_patient = new_patient[input_columns]

    # Predict
    prediction = model.predict(new_patient)[0]

    st.divider()

    st.subheader("Prediction Result")

    if prediction == 1:

        st.error("⚠️ Model Prediction: Diabetes")

        st.write(
            "The model classified this input into "
            "the Diabetes class."
        )

    else:

        st.success("✅ Model Prediction: No Diabetes")

        st.write(
            "The model classified this input into "
            "the No Diabetes class."
        )

    st.info(
        "Important: This is an educational machine learning "
        "demonstration, not a medical diagnosis. The prediction "
        "may be inaccurate. Consult a qualified healthcare "
        "professional for medical assessment."
    )

st.divider()

st.caption(
    "Developed using Python, Pandas, Scikit-learn and Streamlit"
)
